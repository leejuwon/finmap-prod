CREATE TABLE IF NOT EXISTS MARKET_WEEKLY_RECHECK_DIFF (
  diff_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  run_id BIGINT UNSIGNED NOT NULL,
  table_name VARCHAR(80) NOT NULL,
  diff_type ENUM('MISSING_IN_MAIN','MISSING_IN_STAGE','VALUE_DIFF','FLAG_DIFF','ONLY_METADATA_DIFF') NOT NULL,
  target_date VARCHAR(10) NOT NULL COMMENT '비교 대상 운영 날짜 key. 코드 기준 YYYY-MM-DD',
  key_json LONGTEXT NOT NULL COMMENT 'canonical JSON text. key_hash가 unique 기준이므로 JSON 타입 필수 아님',
  -- MySQL 5.7+ JSON 확정 시 대체 가능:
  -- key_json JSON NOT NULL COMMENT '비교 key JSON',
  key_hash BINARY(32) NOT NULL COMMENT '앱에서 UNHEX(SHA2(canonical key_json, 256)) 형태로 계산 권장',
  indicator_code VARCHAR(32) NULL,
  source_id VARCHAR(32) NULL,
  column_name VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'row-level diff는 빈 문자열',
  main_value LONGTEXT NULL,
  stage_value LONGTEXT NULL,
  diff_value DECIMAL(30,10) NULL,
  tolerance DECIMAL(30,10) NULL,
  severity ENUM('HIGH','MEDIUM','LOW') NOT NULL DEFAULT 'MEDIUM',
  resolved_yn CHAR(1) NOT NULL DEFAULT 'N',
  note VARCHAR(1000) NULL,
  checked_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (diff_id),
  UNIQUE KEY uk_market_weekly_diff (run_id, table_name, diff_type, key_hash, column_name),
  KEY idx_market_weekly_diff_run_severity (run_id, severity, diff_type),
  KEY idx_market_weekly_diff_table_date (table_name, target_date),
  KEY idx_market_weekly_diff_indicator (indicator_code, source_id),
  KEY idx_market_weekly_diff_resolved (resolved_yn, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

