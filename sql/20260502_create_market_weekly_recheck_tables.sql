-- Finmap market weekly recheck tables
-- File: sql/20260502_create_market_weekly_recheck_tables.sql
--
-- Scope:
--   신규 검증 테이블 생성만 수행한다.
--   운영 테이블(MARKETS_WORLD_INDICES_INFO, STOCK_INVEST_INFO,
--   MARKET_SITE_ETF_STOCK_INFO 등)에는 ALTER/UPDATE/DELETE/INSERT 하지 않는다.
--
-- Operational DDL status:
--   repo 안에서 운영 3개 마켓 테이블의 CREATE TABLE DDL은 확인되지 않았다.
--   코드 기준 날짜 key 값은 moment/dayjs format('YYYY-MM-DD')로 생성되어 DB에 전달된다.
--   따라서 stage 테이블의 운영 key 날짜 컬럼은 DATE로 고정하지 않고 VARCHAR(10)으로 둔다.
--   운영 DDL 확인 후 실제 타입이 DATE이면 stage도 DATE로 맞추는 것을 검토한다.
--
-- JSON compatibility:
--   운영 MySQL 버전 호환성을 위해 targets/raw_json/key_json은 기본 LONGTEXT로 둔다.
--   MySQL 5.7+ JSON 타입을 확실히 사용할 수 있으면 각 컬럼을 JSON으로 바꿀 수 있다.
--
-- Foreign key policy:
--   기본 DDL에는 FK를 걸지 않는다. 배치/재검증 테이블은 run_id 인덱스와 unique key만으로도
--   조회/비교/삭제 단위를 충분히 제한할 수 있고, 운영 적용 시 FK 검증 비용/잠금 리스크가 작다.
--   FK가 필요하면 파일 하단의 "FK optional" 섹션을 별도 검토 후 적용한다.

-- ============================================================================
-- 1차 적용: run, world-index stage, stock-invest stage, diff
-- ============================================================================

